import { describe, expect, it } from "vitest";
import { triage } from "./triage.js";

const source = "export const a = 1;\n";

describe("triage", () => {
  it.each([
    ["pnpm-lock.yaml", "lockfile"],
    ["apps/web/package-lock.json", "lockfile"],
    ["vendor/github.com/x/y.go", "vendored"],
    ["web/node_modules/zod/index.js", "vendored"],
    ["third_party/lib.c", "vendored"],
    ["public/app.min.js", "generated"],
    ["api/v1/user.pb.go", "generated"],
    ["proto/user_pb2.py", "generated"],
    ["src/__generated__/schema.ts", "generated"],
    ["src/client.generated.ts", "generated"],
    ["dist/index.js", "generated"],
    ["packages/ui/build/index.js", "generated"],
    ["assets/logo.png", "binary"],
  ])("excludes %s as %s", (path, reason) => {
    expect(triage({ path, head: source })).toEqual({ excluded: reason });
  });

  it.each([
    ["src/cart.test.ts", "test"],
    ["app/billing/page.spec.tsx", "test"],
    ["src/__tests__/cart.ts", "test"],
    ["tests/devtools.test.tsx", "test"],
    ["shop/test_cart.py", "test"],
    ["shop/cart_test.py", "test"],
    ["pkg/cart_test.go", "test"],
    ["src/test/java/com/acme/CartTest.java", "test"],
    ["db/migrations/20260930_add_note.sql", "schema"],
    ["prisma/schema.prisma", "schema"],
    ["queries/report.sql", "schema"],
    ["package.json", "manifest"],
    ["services/api/pyproject.toml", "manifest"],
    ["requirements-dev.txt", "manifest"],
    ["pom.xml", "manifest"],
    ["app/build.gradle.kts", "manifest"],
    ["go.mod", "manifest"],
    ["Cargo.toml", "manifest"],
    [".github/workflows/ci.yml", "buildCi"],
    ["Dockerfile", "buildCi"],
    ["deploy/Dockerfile.worker", "buildCi"],
    ["docker-compose.yml", "buildCi"],
    ["Makefile", "buildCi"],
    [".gitlab-ci.yml", "buildCi"],
    ["config/flags.json", "config"],
    ["tsconfig.jsonc", "config"],
    ["k8s/deploy.yaml", "config"],
    ["ruff.toml", "config"],
    [".env.example", "config"],
    ["README.md", "docs"],
    ["content/intro.mdx", "docs"],
    ["docs/diagram.svg", "docs"],
    ["src/cart/totals.ts", "source"],
    ["shop/cart.py", "source"],
  ])("classes %s as %s", (path, fileClass) => {
    expect(triage({ path, head: source })).toEqual({ fileClass });
  });

  it.each([
    ["tests/migrations/0001.sql", "test"],
    ["docs/examples/cart.test.ts", "test"],
    ["docs/package.json", "manifest"],
    [".github/workflows/release.json", "buildCi"],
    ["docs/config.yaml", "config"],
    ["build/package.json", "generated"],
  ])("lets the earlier rule win for %s (%s)", (path, expected) => {
    const result = triage({ path, head: source });
    expect("excluded" in result ? result.excluded : result.fileClass).toBe(expected);
  });

  it("calls a file with a NUL byte near the start binary", () => {
    expect(triage({ path: "data/blob", head: "PK\u0003\u0004\u0000\u0000" })).toEqual({ excluded: "binary" });
    expect(triage({ path: "data/late.txt", head: `${"a".repeat(9_000)}\u0000` })).toEqual({ fileClass: "source" });
  });

  it("excludes a file marked generated in its first five lines", () => {
    expect(triage({ path: "src/api.ts", head: "// Code generated by openapi. DO NOT EDIT.\nexport {};\n" })).toEqual({
      excluded: "generated",
    });
    expect(triage({ path: "src/schema.ts", head: "/**\n * @generated\n */\n" })).toEqual({ excluded: "generated" });
    const late = `${"// header\n".repeat(5)}// @generated mentioned later\n`;
    expect(triage({ path: "src/notes.ts", head: late })).toEqual({ fileClass: "source" });
  });

  it("reads a removed file's base", () => {
    expect(triage({ path: "src/api.ts", base: "// @generated\n" })).toEqual({ excluded: "generated" });
  });

  it("keeps a text file the snapshot left without content", () => {
    expect(triage({ path: "src/huge.ts" })).toEqual({ fileClass: "source" });
  });
});
